import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { mantineHtmlProps } from "@mantine/core";
import "@mantine/core/styles.css";
import "@mantine/dates/styles.css";
import "./globals.css";

import { Providers } from "./providers";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// The same script Mantine's `<ColorSchemeScript>` renders: sets
// data-mantine-color-scheme on <html> before hydration, so there's no flash
// of the wrong theme (see Next's "Preventing flash before hydration" guide,
// node_modules/next/dist/docs/01-app/02-guides/preventing-flash-before-hydration.md).
// Inlined directly here rather than via that component so the `type` swap
// below applies to it. Keep in sync with Providers' MantineProvider (no
// localStorageKey override there, so this uses Mantine's own default key).
const COLOR_SCHEME_SCRIPT = `try {
  var _colorScheme = window.localStorage.getItem("mantine-color-scheme-value");
  var colorScheme = _colorScheme === "light" || _colorScheme === "dark" || _colorScheme === "auto" ? _colorScheme : "dark";
  var computedColorScheme = colorScheme !== "auto" ? colorScheme : window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
  document.documentElement.setAttribute("data-mantine-color-scheme", computedColorScheme);
} catch (e) {}
`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      {...mantineHtmlProps}
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        {/* React warns in dev whenever a rendered <script> has an
            executable type. Since the browser already ran this script
            during initial HTML parsing (before React loads), swapping its
            type to the inert "text/plain" once hydrating on the client
            avoids that warning without changing behavior; the resulting
            server/client type mismatch is exactly what
            suppressHydrationWarning is for. */}
        <script
          data-mantine-script
          type={
            typeof window === "undefined" ? "text/javascript" : "text/plain"
          }
          suppressHydrationWarning
          dangerouslySetInnerHTML={{ __html: COLOR_SCHEME_SCRIPT }}
        />
      </head>
      <body className="flex min-h-full flex-col">
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
